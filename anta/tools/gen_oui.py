"""Regenerate the engine's vendor table (engine/src/oui_data.inc).

The table holds the IEEE OUI assignments of the vendors in
anta.netmap.VENDOR_DISPLAY, under the short names Wireshark shows in its
packet list ("Intel_ec:7e:e7"). They are read from an installed Wireshark:

    python -m anta.tools.gen_oui [path/to/tshark]
"""
from __future__ import annotations

import os
import re
import subprocess
import sys

from anta.netmap import VENDOR_DISPLAY
from anta.tools.compare_wireshark import find_tshark

OUT = os.path.join(os.path.dirname(__file__), "..", "..", "engine", "src", "oui_data.inc")
LINE = re.compile(r"^([0-9A-F]{2}):([0-9A-F]{2}):([0-9A-F]{2})\s*\t([^\t]+)\t")


def main(argv: list[str]) -> int:
    tshark = argv[1] if len(argv) > 1 else find_tshark()
    if not tshark:
        print("gen_oui: tshark not found; pass its path", file=sys.stderr)
        return 1
    dump = subprocess.run([tshark, "-G", "manuf"], capture_output=True, text=True, check=True).stdout
    names = sorted(VENDOR_DISPLAY)
    index = {n: i for i, n in enumerate(names)}
    entries = []
    for line in dump.splitlines():
        m = LINE.match(line)  # 24-bit assignments only (MA-L), not /28 or /36 blocks
        if m and m.group(4).strip() in index:
            prefix = int(m.group(1) + m.group(2) + m.group(3), 16)
            entries.append((prefix, index[m.group(4).strip()]))
    entries.sort()
    out = ["// Generated by anta/tools/gen_oui.py from IEEE OUI assignments (as Wireshark", "// lists them): do not edit.",
           "static const char* const kOuiNames[] = {"]
    for i in range(0, len(names), 6):
        out.append("    " + " ".join(f'"{n}",' for n in names[i:i + 6]))
    out.append("};")
    out.append("// (OUI << 8) | index into kOuiNames, sorted.")
    out.append("static const uint32_t kOuiTable[] = {")
    for i in range(0, len(entries), 8):
        out.append("    " + " ".join(f"0x{p:06X}{v:02X}u," for p, v in entries[i:i + 8]))
    out.append("};")
    with open(OUT, "w") as f:
        f.write("\n".join(out) + "\n")
    print(f"gen_oui: {len(entries)} OUIs for {len(names)} vendors -> {os.path.normpath(OUT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
